// ======================================================
// getUniqueImages
// ======================================================
//
// Эта функция получает массив изображений,
// которые уже прошли Hash Engine.
//
// Одно и то же изображение может встретиться
// на сайте несколько раз.
//
// Например:
//
// test2.jpg → страница 1
// test2.jpg → страница 2
// test2.jpg → страница 3
//
// При этом SHA-256 у всех трёх файлов одинаковый.
//
// Нам нет необходимости три раза запускать ExifTool.
// Достаточно один раз получить метаданные самого файла.
//
// Поэтому функция оставляет только одну запись
// для каждого уникального SHA-256.
// ======================================================

export function getUniqueImages(images) {

    // Map позволяет хранить уникальные значения.
    //
    // Ключом будет SHA-256 изображения.
    //
    // Например:
    //
    // ABC123 → test2.jpg
    // DEF456 → image_2.png
    //
    const uniqueImages = new Map();


    // Перебираем все изображения.
    for (const image of images) {

        // SHA-256 должен быть рассчитан
        // на предыдущем этапе Hash Engine.
        const sha256 = image.sha256;


        // Если SHA-256 отсутствует,
        // использовать его для определения
        // уникальности невозможно.
        //
        // В таком случае используем URL изображения
        // как запасной вариант.
        const key = sha256 || image.imageUrl;


        // Проверяем, добавляли ли мы уже
        // изображение с таким ключом.
        if (!uniqueImages.has(key)) {

            // Если такого изображения ещё нет,
            // сохраняем его в Map.
            //
            // Если это первый test2.jpg,
            // он будет сохранён.
            //
            // Второй и третий test2.jpg
            // уже не будут добавлены.
            uniqueImages.set(key, image);
        }
    }


    // Map содержит только уникальные изображения.
    //
    // Преобразуем его обратно в обычный массив,
    // потому что остальные функции проекта
    // работают с массивами.
    return Array.from(uniqueImages.values());
}